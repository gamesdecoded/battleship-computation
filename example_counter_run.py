#!/usr/bin/env python3
"""Example fleet + counter-search runs for Battleship script v2.
- Example fleet: sampled fleets run through Random, Parity+Target,
  Density, and centre-out best human; the fleet chosen is the one
  closest to the four arm means (not a cherry-picked freak).
- Counter-search: random placements vs edge-aware density, and
  edge placements vs edge-aware density (reproduction check),
  2,000 placements each, same size as the round-1 edge-aware run.
- Origin-drop variant of the best human rule: stack targets are
  dropped on sinking only if they were generated solely by the
  sunk ship's hits; targets also generated by another unsunk hit
  are kept. Compared with the clear-adjacent version on 10,000
  fresh fleets.
Definitions: engine.py (production) + advanced2.py (round 2).
Sunk announcement: a ship is sunk when all its cells are shot.
"""
import json, math, random, sys, time
import numpy as np
sys.path.insert(0, '/home/hatch/workspace/sim-lab/battleship')
import engine as E
import advanced2 as A2

N = 10
FLEET = E.FLEET

def stats(xs):
    xs = np.array(xs, float); n = len(xs)
    m = float(xs.mean()); sd = float(xs.std(ddof=1)) if n > 1 else 0.0
    hw = 1.96 * sd / math.sqrt(n) if n > 1 else 0.0
    return {"n": n, "mean": m, "median": float(np.median(xs)), "sd": sd,
            "ci_half_width": hw, "ci_low": m - hw, "ci_high": m + hw}

def unpaired(a, b):
    sa, sb = stats(a), stats(b)
    d = sa["mean"] - sb["mean"]
    se = math.sqrt(sa["sd"]**2 / sa["n"] + sb["sd"]**2 / sb["n"])
    return {"mean_diff": d, "ci_half_width": 1.96 * se}

def paired(a, b):
    d = np.array(a, float) - np.array(b, float)
    m = float(d.mean()); sd = float(d.std(ddof=1)) if len(d) > 1 else 0.0
    hw = 1.96 * sd / math.sqrt(len(d))
    return {"mean_diff": m, "ci_half_width": hw}

def fmt_fleet(ships):
    # ships: list of sets of cell indices, in fleet order [5,4,3,3,2]
    out = []
    names = ["Carrier (5)", "Battleship (4)", "Cruiser (3)", "Submarine (3)", "Destroyer (2)"]
    for name, s in zip(names, ships):
        cells = sorted(s)
        rows = sorted(set(c // N for c in cells)); cols = sorted(set(c % N for c in cells))
        if len(rows) == 1:
            desc = f"row {rows[0]+1}, columns {cols[0]+1} to {cols[-1]+1}"
        else:
            desc = f"column {cols[0]+1}, rows {rows[0]+1} to {rows[-1]+1}"
        out.append({"ship": name, "cells_0indexed": cells, "description": desc})
    return out

# ---------------- edge-aware density ----------------
# Per-ship counted placements are restricted to placements that touch
# at least one board edge (row 0/9 or column 0/9). This is the round-1
# definition: "density restricted per ship to edge-touching placements
# only" (advanced-investigation.txt, candidate 3).
EDGE_MASK = {}
for L in set(FLEET):
    pls = E.placements_for_length(L)
    EDGE_MASK[L] = np.array([
        any((c // N) in (0, N-1) or (c % N) in (0, N-1) for c in p) for p in pls
    ], dtype=bool)

def edge_aware_scores(rem_lengths, misses, sunk_cells, unsunk_hits):
    blocked = misses | sunk_cells
    barr = np.zeros(N * N, bool)
    for c in blocked:
        barr[c] = True
    scores = np.zeros(N * N, dtype=np.int64)
    hits = sorted(unsunk_hits)
    for L in rem_lengths:
        arr = E.PL_INT[L]; b = E.PL_BOOL[L]
        valid = (~b[:, barr].any(axis=1) if blocked else np.ones(len(arr), bool)) & EDGE_MASK[L]
        if hits:
            ca = valid & b[:, hits].all(axis=1)
            counted = ca if ca.any() else (valid & b[:, hits].any(axis=1))
        else:
            counted = valid
        if counted.any():
            scores += np.bincount(arr[counted].ravel(), minlength=N * N)
    return scores

def play_edge_aware(ships):
    cells = [set(s) for s in ships]; remaining = list(range(len(FLEET)))
    misses = set(); sunk = set(); shot = set(); hits = set(); n = 0
    while remaining:
        rem = [FLEET[i] for i in remaining]
        scores = edge_aware_scores(rem, misses, sunk, hits)
        sq = A2.argmax_centre(scores, shot)
        n += 1; shot.add(sq); hit = None
        for idx in remaining:
            if sq in cells[idx]:
                hit = idx; break
        if hit is None:
            misses.add(sq)
        else:
            hits.add(sq)
            if cells[hit] <= shot:
                remaining.remove(hit); sunk |= cells[hit]; hits -= cells[hit]
    return n

# ---------------- origin-drop best human ----------------
def play_human_origin(ships):
    """Centre-parity hunt, line-only, drop-on-sink by origin.
    Stack entries carry the set of ship indices whose hits generated
    them. On sinking, an entry is dropped only if every ship that
    generated it is the sunk ship (i.e. origin set == {sunk}).
    Entries also generated by another unsunk hit are kept."""
    cells = [set(s) for s in ships]
    cell_to = {}
    for i, s in enumerate(cells):
        for c in s:
            cell_to[c] = i
    remaining = set(range(len(FLEET))); shot = set(); stack = []  # (sq, set(origins))
    unsunk = set(); n = 0
    hunt = sorted([q for q in range(N * N) if (q // N + q % N) % 2 == 0],
                  key=lambda q: (E.DIST2[q], q))
    hi = 0
    def group_of(sq):
        seen = {sq}; fr = [sq]
        while fr:
            cur = fr.pop()
            for nb in E.neighbours(cur):
                if nb in unsunk and nb not in seen:
                    seen.add(nb); fr.append(nb)
        return seen
    def push(sq, origin):
        for e in stack:
            if e[0] == sq:
                e[1].add(origin); return
        stack.append([sq, {origin}])
    while remaining:
        while stack and stack[-1][0] in shot:
            stack.pop()
        if stack:
            sq = stack.pop()[0]
        else:
            while hi < len(hunt) and hunt[hi] in shot:
                hi += 1
            if hi < len(hunt):
                sq = hunt[hi]; hi += 1
            else:
                # Fallback, as in advanced2.play_human: any unshot square, centre first.
                cand = [q for q in range(N * N) if q not in shot]
                cand.sort(key=lambda q: (E.DIST2[q], q)); sq = cand[0]
        n += 1; shot.add(sq); idx = cell_to.get(sq)
        if idx is None or idx not in remaining:
            continue
        unsunk.add(sq); grp = group_of(sq)
        if len(grp) >= 2:
            rows = {g // N for g in grp}; cols = {g % N for g in grp}; ext = []
            if len(rows) == 1:
                r = next(iter(rows)); cs = sorted(g % N for g in grp)
                for cc in (min(cs) - 1, max(cs) + 1):
                    if 0 <= cc < N: ext.append(r * N + cc)
            elif len(cols) == 1:
                c = next(iter(cols)); rs = sorted(g // N for g in grp)
                for rr in (min(rs) - 1, max(rs) + 1):
                    if 0 <= rr < N: ext.append(rr * N + c)
            for e in reversed(ext):
                if e not in shot: push(e, idx)
        else:
            for nb in E.neighbours(sq):
                if nb not in shot: push(nb, idx)
        if cells[idx] <= shot:
            remaining.remove(idx); unsunk -= cells[idx]
            stack = [e for e in stack if e[1] != {idx}]
    return n

def main():
    seed = 20291120
    out = {"seed": seed}
    # ---- example fleet selection: 300 fleets, 4 arms ----
    frng = random.Random(seed)
    fleets = [E.sample_fleet(frng) for _ in range(300)]
    t0 = time.time()
    rnd = [E.play_random(f, random.Random(seed + 1000000 + i)) for i, f in enumerate(fleets)]
    par = [E.play_target(f, random.Random(seed + 3000000 + i), parity=True) for i, f in enumerate(fleets)]
    den = [E.play_density(f) for f in fleets]
    hum = [A2.play_human(f, random.Random(seed + 3600000 + i), hunt_mode='centre_parity',
                         clear_on_sink='adjacent', line_only=True) for i, f in enumerate(fleets)]
    arms = {"Random": rnd, "Parity+Target": par, "Density": den, "BestHuman-centre": hum}
    arm_stats = {k: stats(v) for k, v in arms.items()}
    # distance to means, in SD units, summed over arms
    best_i, best_d = None, 1e18
    for i in range(300):
        d = sum(abs(arms[k][i] - arm_stats[k]["mean"]) / arm_stats[k]["sd"] for k in arms)
        if d < best_d:
            best_d, best_i = d, i
    ex = fleets[best_i]
    out["example_fleet"] = {
        "selection": "300 sampled fleets, each run through all four arms; chosen fleet minimises "
                     "sum over arms of |count - arm mean| / arm SD (closest to the arm means, "
                     "not a cherry-picked freak). Arm means over the 300 are reported alongside.",
        "index_in_sample": best_i, "distance_sd_units": best_d,
        "ships": fmt_fleet(ex),
        "shot_counts": {k: arms[k][best_i] for k in arms},
        "arm_means_300": {k: round(arm_stats[k]["mean"], 2) for k in arms},
        "arm_sds_300": {k: round(arm_stats[k]["sd"], 2) for k in arms},
    }
    print(f"example fleet idx {best_i} dist {best_d:.2f} counts {out['example_fleet']['shot_counts']} "
          f"means {out['example_fleet']['arm_means_300']} ({time.time()-t0:.1f}s)", flush=True)
    # ---- counter-search: 2,000 random + 2,000 edge placements vs edge-aware ----
    prng = random.Random(seed + 5000000)
    rand_pl = [E.sample_placement(prng, E.PLACEMENT_STRATEGIES["P-random"][0]) for _ in range(2000)]
    edge_pl = [E.sample_placement(prng, E.PLACEMENT_STRATEGIES["P-edge"][0]) for _ in range(2000)]
    t0 = time.time()
    ea_rand = [play_edge_aware(f) for f in rand_pl]
    ea_edge = [play_edge_aware(f) for f in edge_pl]
    out["counter_search"] = {
        "definition": "Edge-aware density: group-all marginal placement-count, but per ship only "
                      "edge-touching placements are counted (round-1 definition).",
        "n_per_strategy": 2000,
        "random_vs_edge_aware": stats(ea_rand),
        "edge_vs_edge_aware": stats(ea_edge),
        "unpaired_edge_minus_random_vs_edge_aware": unpaired(ea_edge, ea_rand),
        "round1_edge_vs_edge_aware_for_comparison": 32.97,
        "note": "Same-searcher comparison is edge vs edge-aware against random vs edge-aware. "
                "Comparing edge vs edge-aware with random vs plain density mixes searchers and is not used.",
    }
    print(f"edge-aware: random {stats(ea_rand)['mean']:.2f} edge {stats(ea_edge)['mean']:.2f} "
          f"diff {unpaired(ea_edge, ea_rand)} ({time.time()-t0:.1f}s)", flush=True)
    # ---- origin-drop variant: 10,000 fresh fleets ----
    frng2 = random.Random(seed + 9000000)
    fleets2 = [E.sample_fleet(frng2) for _ in range(10000)]
    t0 = time.time()
    hum_adj = [A2.play_human(f, random.Random(seed + 3600000 + i), hunt_mode='centre_parity',
                             clear_on_sink='adjacent', line_only=True) for i, f in enumerate(fleets2)]
    hum_org = [play_human_origin(f) for f in fleets2]
    out["origin_drop_variant"] = {
        "n": 10000,
        "best_human_clear_adjacent": stats(hum_adj),
        "best_human_origin_only": stats(hum_org),
        "paired_origin_minus_adjacent": paired(hum_org, hum_adj),
        "reading": "If the paired difference is small, the script's origin-only drop wording "
                   "describes the measured rule to within that difference; the script numbers "
                   "remain the verified clear-adjacent numbers unless the difference is material.",
    }
    print(f"origin: adjacent {stats(hum_adj)['mean']:.2f} origin {stats(hum_org)['mean']:.2f} "
          f"paired {paired(hum_org, hum_adj)} ({time.time()-t0:.1f}s)", flush=True)
    with open('/home/hatch/workspace/sim-lab/battleship/example_counter_run.json', 'w') as fh:
        json.dump(out, fh, indent=2)
    print("wrote example_counter_run.json", flush=True)

if __name__ == '__main__':
    main()
